import type { DisasterType, Evidence, ReliefCenter, SosRequest, SosPriority } from "./intel";
import { scorePriority } from "./intel";

export interface TimelineEntry {
  time: string;
  label: string;
  kind: "evidence" | "ai" | "gap" | "response";
}

export interface Scenario {
  key: Exclude<DisasterType, "none" | "landslide">;
  label: string;
  area: string;
  center: { lat: number; lng: number };
  evidence: Evidence[];
  sos: SosRequest[];
  centers: ReliefCenter[];
  timeline: TimelineEntry[];
  /** Evidence that arrives when the operator accepts the recommended observation. */
  followUp: Evidence;
}

const iso = (minutesAgo: number) => new Date(Date.now() - minutesAgo * 60_000).toISOString();

function sos(
  partial: Omit<SosRequest, "priority" | "status" | "timestamp"> & {
    status?: SosRequest["status"];
    minutesAgo?: number;
  },
): SosRequest {
  const base = {
    ...partial,
    status: partial.status ?? ("NEW" as const),
    timestamp: iso(partial.minutesAgo ?? 20),
  };
  const priority: SosPriority = scorePriority(base);
  return { ...base, priority };
}

